# Every membership the prose above and in render_filtering_block states, as
# (tool, group, is a member). Checked against the collected groups on every run, so
# a tool moving between groups fails the run instead of leaving a false claim.
# The spreadsheet tools under tools/drive/, in `sheets` too (#1511);
# tests/test_tool_groups.py checks this list against the tools.
SPREADSHEET_FILE_TOOLS = (
    "create_spreadsheet",
    "list_spreadsheets",
    "search_spreadsheets",
    "import_csv_to_sheet",
    "share_spreadsheet",
)
MEMBERSHIP_CLAIMS = (
    ("create_spreadsheet", tool_groups.DEFAULT, True),
    # "searching ... spreadsheets" in the `sheets` description: search_files absorbs
    # search_spreadsheets and list_spreadsheets (#1528).
    ("search_files", "sheets", True),
    *((name, "sheets", True) for name in SPREADSHEET_FILE_TOOLS),
    *((name, "drive", True) for name in SPREADSHEET_FILE_TOOLS),
)

# The local-file tools "What `default` leaves out" names. Each must be in
# `local-files` and not in `default`.
DEFAULT_LEAVES_OUT = (
    "upload_local_file",
    "download_folder",
    "sync_folder",
    "import_csv_to_sheet",
    "create_doc_from_file",
    "update_doc_from_file",
)

# Windsurf caps a session at 100 tools across every server, the lowest
# documented client limit. Every group but `all` must stay under it, so a group
# that grows past it fails the run instead of documenting a broken setup.
CLIENT_TOOL_LIMIT = 100
# Older Cursor builds capped a session at 40 tools across every server
# (docs/client-setup.md); the Tool filtering section says where `default` stands.
OLD_CURSOR_TOOL_LIMIT = 40


def group_members(groups_by_name: dict[str, frozenset[str]]) -> dict[str, list[str]]:
    """Each documented group's tools, in registration order. `all` holds every tool."""
    members: dict[str, list[str]] = {name: [] for name in GROUP_DESCRIPTIONS}
    for tool_name, groups in groups_by_name.items():
        members[tool_groups.ALL].append(tool_name)
        for group in groups:
            members[group].append(tool_name)
    return members


def check_claims(members: dict[str, list[str]]) -> None:
    """Fail the run on a membership the prose states that the tools don't bear out."""
    claims = [
        *MEMBERSHIP_CLAIMS,
        *((name, tool_groups.LOCAL_FILES, True) for name in DEFAULT_LEAVES_OUT),
        *((name, tool_groups.DEFAULT, False) for name in DEFAULT_LEAVES_OUT),
    ]
    wrong = [
        f"{name} {'in' if expected else 'not in'} {group}"
        for name, group, expected in claims
        if (name in members[group]) != expected
    ]
    if wrong:
        raise RuntimeError(
            "gen_tool_docs: the Tool filtering prose claims "
            f"{'; '.join(wrong)}, which the tools don't bear out. Update "
            "MEMBERSHIP_CLAIMS, DEFAULT_LEAVES_OUT or the prose in scripts/gen_tool_docs.py."
        )


_CODE_SPAN = re.compile(r"`([^`\n]+)`")
_NAME_LIKE = re.compile(r"[a-z][a-z0-9_-]*")


def check_names(text: str, known: set[str]) -> None:
    """Fail the run on a lowercase name in a code span (or one entry of a
    comma-separated one, like `default,local-files`) that names no tool or group.
    Fenced blocks are skipped: the `default` list there is built from the tools."""
    text = re.sub(r"```.*?```", "", text, flags=re.DOTALL)
    names = {
        entry
        for span in _CODE_SPAN.findall(text)
        for entry in span.split(",")
        if _NAME_LIKE.fullmatch(entry)
    }
    unknown = sorted(names - known - tool_groups.GROUP_NAMES)
    if unknown:
        raise RuntimeError(
            f"gen_tool_docs: the Tool filtering section names {', '.join(unknown)}, "
            "which is no tool or group. Update scripts/gen_tool_docs.py."
        )


def format_groups(groups: frozenset[str], module: str) -> str:
    """A tool's groups for its docs/tools.md row: the service group of its own module
    first, then any other service group, then the rest."""
    home = tool_groups.service_group(module)
    services = [g for g in tool_groups.SERVICE_GROUPS if g in groups and g != home]
    if home in groups:
        services.insert(0, home)
    others = sorted(groups - set(services))
    return ", ".join(f"`{g}`" for g in [*services, *others])


def render_tools_md(funcs, groups_by_name: dict[str, frozenset[str]]) -> str:
    lines = [
        "# Tool Reference",
        "",
        GENERATED_BANNER,
        "",
        f"{len(funcs)} tools. All tool names are lowercase with underscores — use "
        "these exact strings with `ENABLED_TOOLS` or `--include-tools`. The Groups "
        "column names the [tool groups](configuration.md#tool-groups) that load each "
        "tool, and `all` loads every one.",
        "",
    ]
    seen = set()
    for title, predicate, notes in SECTIONS:
        matched = [f for f in funcs if predicate(f)]
        seen.update(matched)
        lines.append(f"## {title}")
        lines.append("")
        lines.append("| Tool | Description | Key parameters | Groups |")
        lines.append("|---|---|---|---|")
        for func in matched:
            lines.append(
                f"| `{func.__name__}` | {summary(func)} | {param_list(func)} "
                f"| {format_groups(groups_by_name[func.__name__], func.__module__)} |"
            )
        lines.append("")
        if notes:
            lines.append(notes)
            lines.append("")

    unmatched = [f for f in funcs if f not in seen]
    if unmatched:
        names = ", ".join(sorted(f.__name__ for f in unmatched))
        raise RuntimeError(
            f"gen_tool_docs: no SECTIONS entry matches these tools: {names}. "
            "Add a section (or predicate) for them in scripts/gen_tool_docs.py."
        )

    lines.append(MCP_RESOURCES)
    return "\n".join(lines).rstrip() + "\n"


def render_filtering_block(groups_by_name: dict[str, frozenset[str]]) -> str:
    """The "Tool filtering" section of docs/configuration.md."""
    missing = sorted(tool_groups.GROUP_NAMES - set(GROUP_DESCRIPTIONS))
    extra = sorted(set(GROUP_DESCRIPTIONS) - tool_groups.GROUP_NAMES)
    if missing or extra:
        raise RuntimeError(
            "gen_tool_docs: GROUP_DESCRIPTIONS doesn't match tool_groups.GROUP_NAMES "
            f"(undocumented: {', '.join(missing) or 'none'}; unknown: "
            f"{', '.join(extra) or 'none'}). Update scripts/gen_tool_docs.py."
        )
    members = group_members(groups_by_name)
    for group, names in members.items():
        if not names:
            raise RuntimeError(f"gen_tool_docs: tool group {group!r} has no tools.")
        if group != tool_groups.ALL and len(names) >= CLIENT_TOOL_LIMIT:
            raise RuntimeError(
                f"gen_tool_docs: tool group {group!r} has {len(names)} tools, at or over "
                f"the {CLIENT_TOOL_LIMIT}-tool client limit every group but `all` is "
                "documented to fit under."
            )
    check_claims(members)
    default_names = members[tool_groups.DEFAULT]
    # `all` also registers every deprecated alias (tool_groups.RENAMED_TOOLS), so its
    # count is what a client actually receives under it.
    counts = {group: len(names) for group, names in members.items()}
    counts[tool_groups.ALL] += len(tool_groups.RENAMED_TOOLS)
    lines = [
        "## Tool filtering",
        "",
        GENERATED_BANNER,
        "",
        f"By default the server registers the `default` tool group, {len(default_names)} "
        f"of the {len(groups_by_name)} tools. Use `ENABLED_TOOLS` (or `--include-tools` "
        "on the CLI) to choose the tools you need: it takes tool names and group names, "
        "and the server registers their union. Fewer tools reduce the AI's context "
        "window cost — each registered tool is a name the model must reason about on "
        "every call.",
        "",
        "```bash",
        "# Environment variable: the default set, plus the local-file tools",
        "ENABLED_TOOLS=default,local-files",
        "",
        "# CLI flag: every Docs tool, plus one Calendar tool",
        "uv run mcp-gee-sweet --include-tools docs,list_events",
        "```",
        "",
        "If neither is set, or the value is empty, the `default` group is registered. "
        "`ENABLED_TOOLS=all` (or `--include-tools all`) registers every tool. Listed "
        "with other entries, `all` still registers every tool. Entries are "
        "case-sensitive, and one that names no tool or group (`ALL`, a typo) is logged "
        "as a warning at startup and otherwise ignored. The startup log, the server's "
        "instructions to the client, and `server://auth-status` each say which tools "
        "loaded. `ENABLED_TOOLS` also decides which Google scopes the server asks for: "
        "with no Gmail tool selected, it never asks for mailbox access.",
        "",
        "### Tool groups",
        "",
        "| Group | Tools | What it holds |",
        "|---|---|---|",
    ]
    for group, description in GROUP_DESCRIPTIONS.items():
        tools = ", ".join(f"`{name}`" for name in members[group])
        lines.append(f"| `{group}` | {counts[group]} | {description.format(tools=tools)} |")
    lines += [
        "",
        "Each tool's groups are listed in [Tools](tools.md). A group never loads a "
        "deprecated alias: only `all`, or the old name itself, does.",
        "",
        "**What `default` holds:**",
        "```",
        ",".join(default_names),
        "```",
        "",
        "**What `default` leaves out.** It has no tool that only works on local files, "
        "so local upload, download and sync, CSV import, and the Markdown file tools ("
        + ", ".join(f"`{name}`" for name in DEFAULT_LEAVES_OUT)
        + ", ...) need `local-files` or their "
        "own names. It also leaves out most structural tools: Sheets formatting and "
        "charts, Docs tables and themes, file comments, calendar management, and Drive "
        "trash. Add a service group, or the tool names, for those.",
        "",
        "**Combining entries.** Join groups and names with a comma, e.g. "
        "`default,local-files` or `default,comments,insert_doc_table`; a tool named "
        "twice loads once. Some MCP clients cap how many tools they accept, and every "
        f"group but `all` is under {CLIENT_TOOL_LIMIT}, the lowest cap a current client "
        f"documents. {_old_cursor_note(len(default_names))} A combination can go over "
        "a cap. Adding up the counts above gives an upper bound, since groups overlap "
        "and a tool in two loads once; Windsurf's cap also counts every other "
        "server's tools. See [Clients with a tool limit]"
        "(client-setup.md#clients-with-a-tool-limit) for each client's setting.",
        "",
    ]
    check_names("\n".join(lines), set(groups_by_name))
    return "\n".join(lines)


def _old_cursor_note(default_count: int) -> str:
    """Where `default` stands against the 40-tool cap of older Cursor builds."""
    limit = OLD_CURSOR_TOOL_LIMIT
    if default_count < limit:
        return f"`default` ({default_count}) is also under the {limit} older Cursor builds allowed."
    if default_count == limit:
        return (
            f"`default` ({default_count}) is exactly the {limit} older Cursor builds "
            "allowed, so there it leaves no room for another server's tools."
        )
    return f"`default` ({default_count}) is over the {limit} older Cursor builds allowed."


def write_if_changed(path: Path, content: str) -> bool:
    if path.exists() and path.read_text() == content:
        return False
    path.write_text(content)
    return True


def main() -> int:
    groups_by_name: dict[str, frozenset[str]] = {}
    funcs = collect_tools(groups_by_name)
    require_docstrings(funcs)

    changed = write_if_changed(TOOLS_MD, render_tools_md(funcs, groups_by_name))

    config_text = CONFIG_MD.read_text()
    new_block = render_filtering_block(groups_by_name)
    # backslash-escape the replacement so re.sub doesn't treat it as a backreference template
    escaped_block = new_block.replace("\\", "\\\\") + "\n"
    updated_config, n_subs = re.subn(
        r"## Tool filtering\n.*?\n(?=## )",
        escaped_block,
        config_text,
        count=1,
        flags=re.DOTALL,
    )
    if n_subs == 0:
        raise RuntimeError(
            "gen_tool_docs: could not find '## Tool filtering' section in "
            f"{CONFIG_MD.relative_to(ROOT)} to replace."
        )
    if updated_config != config_text:
        CONFIG_MD.write_text(updated_config)
        changed = True

    if changed:
        print("gen_tool_docs: regenerated docs/tools.md and/or docs/configuration.md")
        return 1
    print("gen_tool_docs: docs already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
